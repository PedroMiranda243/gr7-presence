class Translator:
    def __init__(self, language: str = "pt"):
        self.language = language if language in STRINGS else "pt"

    def __call__(self, key: str, **kwargs) -> str:
        text = STRINGS[self.language].get(key) or STRINGS["pt"].get(key, key)
        return text.format(**kwargs) if kwargs else text


def format_time(seconds: float, long: bool = False) -> str:
    """Para a janela: 2520 -> '42 min', 21120 -> '5 h 52' (ou '5 h 52 min' com `long`), 309600 -> '86 h'."""
    minutes = int(seconds // 60)
    if minutes < 60:
        return f"{minutes} min"
    hours, minutes = divmod(minutes, 60)
    if not minutes:
        return f"{hours} h"
    return f"{hours} h {minutes} min" if long else f"{hours} h {minutes:02d}"


def format_duration(seconds: float) -> str:
    """3725 -> '1h02', 540 -> '9min', 30 -> '0min'."""
    minutes = int(seconds // 60)
    hours, minutes = divmod(minutes, 60)
    if hours >= 100:
        return f"{hours}h"
    if hours:
        return f"{hours}h{minutes:02d}"
    return f"{minutes}min"
